_icon_cache = {}

def get_icon(name: str, color: str = "#94A3B8", size: int = 20) -> QIcon:
    """Generate a high-DPI QIcon from SVG path with specified color and size."""
    cache_key = f"{name}_{color}_{size}"
    if cache_key in _icon_cache:
        return _icon_cache[cache_key]

    template = SVG_TEMPLATES.get(name)
    if not template:
        return QIcon()

    svg_content = template.format(color=color)
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(QColor("transparent"))
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    icon = QIcon(pixmap)
    _icon_cache[cache_key] = icon
    return icon
